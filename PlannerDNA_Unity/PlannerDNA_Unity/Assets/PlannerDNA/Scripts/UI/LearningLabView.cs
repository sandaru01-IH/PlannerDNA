    /// <summary>
    /// Learning Lab: training data coverage, the explicit "Train my model" action, the fitted model's
    /// weights with uncertainty, diagnostics against simple baselines, history, and model-ranked
    /// suggestions. Everything shown comes from the local backend; nothing is computed or invented here.
    /// </summary>
    public sealed class LearningLabView
    {
        public const int SuggestionCount = 5;
        public const float SyncWaitSeconds = 20f;

        private const string Banner =
            "Synthetic scenarios only. A model is a statistical summary of associations in YOUR OWN past A/B choices. " +
            "It does not understand planning, its only fair check is the blinded test at the bottom of this page, and " +
            "its suggestions are never 'optimal'.";

        private const string EvaluationNote =
            "The numbers above come from the same choices the model was trained on. The blinded test checks the frozen model " +
            "on new areas instead: each prediction is sealed before you choose and opened only when you finish.";

        private const string SuggestBanner =
            "SYNTHETIC SCENARIO. Candidates are generated by fixed rules, filtered for feasibility here, and ordered by your " +
            "fitted model. They are suggestions to inspect, not recommendations or optimal plans.";

        private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        private readonly SandboxUi _ui;
        private readonly PlannerApp _app;
        private readonly VisualElement _screen, _weights, _diagnostics, _history, _suggestList;
        private readonly Label _samples, _readinessLabel, _warning, _trainStatus, _model, _tradeoffs, _diagNote, _caveats,
            _historyNote, _suggestBanner, _suggestStatus, _evalNote;
        private readonly Button _train, _suggest;

        private int _generation;
        private int _inflight;
        private bool _training, _ranking;
        private CandidateSet _lastSet;

        public ReadinessDto LastReadiness { get; private set; }
        public CurrentModelDto LastCurrent { get; private set; }
        public ModelHistoryDto LastHistory { get; private set; }
        public RankResponseDto LastRank { get; private set; }
        public string LastError { get; private set; }
        public bool IsBusy => _inflight > 0 || _training || _ranking;
        public bool IsOpen => !_screen.ClassListContains("hidden");
        public bool TrainEnabled => _train.enabledSelf;
        public bool SuggestEnabled => _suggest.enabledSelf;
        public string SamplesText => _samples.text;
        public string TrainStatusText => _trainStatus.text;
        public string ModelText => _model.text;
        public string SuggestStatusText => _suggestStatus.text;
        public int WeightRows => Math.Max(0, _weights.childCount - 1);
        public int SuggestionCards => _suggestList.childCount;

        public LearningLabView(SandboxUi ui, PlannerApp app)
        {
            _ui = ui;
            _app = app;
            _screen = ui.Q<VisualElement>("learning-screen");
            _samples = ui.Q<Label>("learning-samples");
            _readinessLabel = ui.Q<Label>("learning-readiness");
            _warning = ui.Q<Label>("learning-warning");
            _train = ui.Q<Button>("btn-train");
            _trainStatus = ui.Q<Label>("learning-train-status");
            _model = ui.Q<Label>("learning-model");
            _weights = ui.Q<VisualElement>("learning-weights");
            _tradeoffs = ui.Q<Label>("learning-tradeoffs");
            _diagNote = ui.Q<Label>("learning-diagnostics-note");
            _diagnostics = ui.Q<VisualElement>("learning-diagnostics");
            _caveats = ui.Q<Label>("learning-caveats");
            _historyNote = ui.Q<Label>("learning-history-note");
            _history = ui.Q<VisualElement>("learning-history");
            _suggestBanner = ui.Q<Label>("suggest-banner");
            _suggest = ui.Q<Button>("btn-suggest");
            _suggestStatus = ui.Q<Label>("suggest-status");
            _suggestList = ui.Q<VisualElement>("suggest-list");
            _evalNote = ui.Q<Label>("learning-eval-note");

            ui.Q<Label>("learning-banner").text = Banner;
            _evalNote.text = EvaluationNote;
            ui.Q<Button>("btn-open-evaluation").clicked += ui.OpenEvaluation;
            _suggestBanner.text = SuggestBanner;
            _train.clicked += Train;
            _suggest.clicked += Suggest;
            ui.Q<Button>("btn-learning-refresh").clicked += Refresh;
            ui.Q<Button>("btn-learning-close").clicked += () => ui.CloseOverlay(_screen);
        }

        public void Open()
        {
            _ui.OpenOverlay(_screen);
            Refresh();
        }

        // ---- Loading ----

        public void Refresh()
        {
            int generation = ++_generation;
            LastError = null;
            if (!_app.Learning.Available)
            {
                LastReadiness = null;
                LastCurrent = null;
                LastHistory = null;
                RenderOffline();
                UpdateButtons();
                return;
            }
            _samples.text = "Checking the local backend...";
            UpdateButtons();
            Begin();
            _app.Learning.FetchReadiness(r =>
            {
                End();
                if (generation != _generation) return;
                if (r.Ok) LastReadiness = r.Body; else Fail(r.Code, r.Message);
                RenderReadiness();
                UpdateButtons();
            });
            Begin();
            _app.Learning.FetchCurrent(r =>
            {
                End();
                if (generation != _generation) return;
                if (r.Ok) LastCurrent = r.Body; else Fail(r.Code, r.Message);
                RenderModel();
                UpdateButtons();
            });
            Begin();
            _app.Learning.FetchHistory(r =>
            {
                End();
                if (generation != _generation) return;
                if (r.Ok) LastHistory = r.Body; else Fail(r.Code, r.Message);
                RenderHistory();
            });
        }

        /// <summary>Called on health and sync changes; refetches only when availability or the active model changed.</summary>
        public void OnHealthChanged()
        {
            string key = _app.Learning.Available + "|" + (_app.Health != null ? _app.Health.ActiveModelVersion : string.Empty);
            bool changed = key != _healthKey;
            _healthKey = key;
            if (IsOpen && changed && !IsBusy) Refresh();
            else
            {
                if (LastReadiness != null && _app.Learning.Available) RenderReadiness();
                UpdateButtons();
            }
        }

        private string _healthKey;

        private void Begin() => _inflight++;
        private void End() => _inflight = Math.Max(0, _inflight - 1);

        private void Fail(string code, string message)
        {
            LastError = $"{code}: {message}";
            _ui.ShowMessage($"Learning Lab: {message} ({code})", true);
        }

        private void RenderOffline()
        {
            string local;
            try
            {
                PreferenceStats s = _app.Store.ComputeStats();
                local = $"Stored on this computer: {s.unique_comparisons} decision(s) across {s.scenarios} scenario(s).";
            }
            catch (Exception e) when (e is System.IO.IOException || e is UnauthorizedAccessException)
            {
                local = "Could not read local decisions: " + e.Message;
            }
            _samples.text = "Training samples: unknown while the backend is offline. " + local;
            _readinessLabel.text = _app.Learning.UnavailableReason +
                                   " Models are trained and stored only by the local backend (127.0.0.1); see docs/runbook.md.";
            SetWarning(null);
            _model.text = "No model information is available offline, so no weights or predictions are shown.";
            Hide(_weights);
            _tradeoffs.text = string.Empty;
            _diagNote.text = string.Empty;
            Hide(_diagnostics);
            _caveats.text = Banner;
            _historyNote.text = string.Empty;
            Hide(_history);
            _suggestList.Clear();
        }

        // ---- Readiness and training ----

        private void RenderReadiness()
        {
            ReadinessDto r = LastReadiness;
            if (r == null)
            {
                _samples.text = "Training data status unavailable.";
                return;
            }
            _samples.text = $"Training samples: {r.informative_comparisons} unique direct comparisons across {r.scenarios} scenarios";
            var lines = new List<string>();
            foreach (ReadinessReasonDto reason in r.reasons) lines.Add("Cannot train yet: " + reason.message);
            if (r.can_train) lines.Add("Enough varied comparisons to fit a model.");
            ThresholdsDto t = r.thresholds;
            if (t != null)
                lines.Add($"Minimum to train: {t.min_comparisons} informative comparisons from {t.min_scenarios} scenarios that vary in at " +
                          $"least {t.min_rank} independent directions. Suggested before trusting results: {t.suggested_comparisons} " +
                          $"comparisons across {t.suggested_scenarios} scenarios (a heuristic, not a statistical guarantee).");
            ExcludedCountsDto x = r.excluded;
            if (x != null && x.ties_and_skips + x.evaluation_mode + x.infeasible > 0)
                lines.Add($"Of {x.all_comparisons} stored decision(s), not used for training: {x.ties_and_skips} tie/skip, " +
                          $"{x.evaluation_mode} evaluation-mode and {x.infeasible} infeasible-pair decision(s).");
            _readinessLabel.text = string.Join("\n", lines);

            var warnings = new List<string>(r.warnings);
            int pending = _app.Outbox.PendingCount;
            if (pending > 0) warnings.Insert(0, $"{pending} local record(s) have not reached the backend yet; they are not counted above.");
            SetWarning(warnings.Count > 0 ? string.Join("\n", warnings) : null);
        }

        private void SetWarning(string text)
        {
            _warning.text = text ?? string.Empty;
            _warning.EnableInClassList("hidden", string.IsNullOrEmpty(text));
        }

        public void Train()
        {
            if (!_train.enabledSelf || _training) return;
            _training = true;
            _trainStatus.text = "Training on the local backend...";
            UpdateButtons();
            _app.Learning.Train(r =>
            {
                _training = false;
                if (r.Ok && r.Body.model != null)
                {
                    ModelSummaryDto m = r.Body.model;
                    _trainStatus.text = r.Body.status == "created"
                        ? $"Trained model {m.model_version} on {m.unique_comparisons} comparisons across {m.scenario_count} scenarios."
                        : $"No new training data since {m.model_version}; the existing model was kept (identical data gives an identical model).";
                    _ui.ShowMessage(_trainStatus.text, false);
                }
                else
                {
                    _trainStatus.text = $"Training refused ({r.Code}): {r.Message}";
                    LastError = $"{r.Code}: {r.Message}";
                }
                _app.Health?.RefreshNow();
                Refresh();
            });
        }

        // ---- Model ----

        private void RenderModel()
        {
            CurrentModelDto c = LastCurrent;
            ModelSummaryDto m = c != null && c.has_model ? c.model : null;
            _weights.Clear();
            _diagnostics.Clear();
            if (m == null)
            {
                _model.text = "No model has been trained yet. No weights, predictions or suggestions are shown until you train one; " +
                              "PlannerDNA never substitutes fixed weights.";
                Hide(_weights);
                _tradeoffs.text = string.Empty;
                _diagNote.text = "Diagnostics appear after training.";
                Hide(_diagnostics);
                _caveats.text = Banner;
                return;
            }

            _model.text =
                $"Model version {m.model_version} ({m.status}), trained {m.trained_utc}.\n" +
                $"{m.model_kind}, {m.ml_version}, {m.feature_version}, seed {m.random_seed}. " +
                $"{m.unique_comparisons} comparisons across {m.scenario_count} scenarios ({m.choices_for_a} chose A, {m.choices_for_b} chose B)." +
                (string.IsNullOrEmpty(m.summary) ? string.Empty : "\n" + m.summary);

            Row(_weights, true, "Feature", "Weight (std.)", $"{Level(m)} interval", "Same sign", "What it means");
            foreach (CoefficientDto k in m.coefficients)
            {
                bool estimated = k.varied;
                Row(_weights, false, k.label,
                    estimated ? k.weight_standardised.ToString("+0.00;-0.00;0.00", Inv) : "n/a",
                    estimated ? $"[{k.interval_low.ToString("0.00", Inv)}, {k.interval_high.ToString("0.00", Inv)}]" : "n/a",
                    estimated && k.direction != "negligible" ? (k.sign_agreement * 100).ToString("0", Inv) + "%" : "-",
                    k.statement);
            }
            Show(_weights);
            _tradeoffs.text = Tradeoffs(m);

            DiagnosticsDto d = m.diagnostics;
            string fit = m.training_fit != null
                ? $" Training fit (optimistic, same data): accuracy {Pct(m.training_fit.accuracy)}."
                : string.Empty;
            if (d != null && d.available && d.model != null)
            {
                _diagNote.text = d.note + $" {d.folds} fold(s), {d.skipped_folds} skipped." + fit;
                Row(_diagnostics, true, "Predictor", "n", "Accuracy", "Brier", "Log loss");
                Row(_diagnostics, false, "Your model (predicted without its scenario)", d.model.n.ToString(Inv), Pct(d.model.accuracy),
                    d.model.brier.ToString("0.000", Inv), d.model.has_log_loss ? d.model.log_loss.ToString("0.000", Inv) : "-");
                foreach (BaselineScoreDto b in d.baselines)
                    Row(_diagnostics, false, "Baseline: " + b.label, b.n.ToString(Inv), Pct(b.accuracy), b.brier.ToString("0.000", Inv),
                        b.has_log_loss ? b.log_loss.ToString("0.000", Inv) : "-");
                Show(_diagnostics);
            }
            else
            {
                _diagNote.text = (d != null && !string.IsNullOrEmpty(d.note) ? d.note : "Diagnostics are unavailable for this model.") + fit;
                Hide(_diagnostics);
            }

            var caveats = new List<string>();
            foreach (string w in m.warnings) caveats.Add("Warning: " + w);
            foreach (string cv in m.caveats) caveats.Add(cv);
            _caveats.text = caveats.Count > 0 ? "- " + string.Join("\n- ", caveats) : Banner;
        }

        private static string Level(ModelSummaryDto m)
        {
            foreach (CoefficientDto k in m.coefficients)
                if (k.interval_level > 0) return (k.interval_level * 100).ToString("0", Inv) + "%";
            return "Bootstrap";
        }

        /// <summary>Model-implied exchange rates, shown only when both weights are clearly estimated and positive.</summary>
        private string Tradeoffs(ModelSummaryDto m)
        {
            CoefficientDto access = Find(m, "delta_access_fraction");
            CoefficientDto budget = Find(m, "negative_budget_fraction");
            CoefficientDto housing = Find(m, "delta_housing_fraction");
            var parts = new List<string>();
            if (Usable(access) && Usable(budget))
            {
                double share = 0.01 * access.weight_raw / budget.weight_raw;
                string credits = _app.Session != null
                    ? $" (about {(share * _app.Session.Scenario.BudgetLimit).ToString("0", Inv)} credits in this scenario)"
                    : string.Empty;
                parts.Add($"+1 percentage point of park access is weighted like spending {Pct(share)} of the budget{credits}");
            }
            if (Usable(access) && Usable(housing))
            {
                double share = 0.01 * access.weight_raw / housing.weight_raw;
                parts.Add($"+1 percentage point of park access is weighted like {Pct(share)} of baseline housing capacity");
            }
            var shares = new List<string>();
            var ranked = new List<CoefficientDto>(m.coefficients);
            ranked.Sort((x, y) => y.relative_importance.CompareTo(x.relative_importance));
            foreach (CoefficientDto k in ranked)
                if (k.varied) shares.Add($"{k.label} {(k.relative_importance * 100).ToString("0", Inv)}%");
            string importance = "Share of total standardised weight: " + string.Join(", ", shares) + ".";
            if (parts.Count == 0)
                return importance + "\nNo exchange rate is shown: that needs park access and the compared outcome (spending or housing) " +
                       "to both have positive weights whose intervals exclude zero.";
            return importance + "\nModel-implied trade-offs: " + string.Join("; ", parts) +
                   ". These are statistical associations in your past choices, not valuations, and they are uncertain.";
        }

        private static CoefficientDto Find(ModelSummaryDto m, string feature)
        {
            foreach (CoefficientDto k in m.coefficients)
                if (k.feature == feature) return k;
            return null;
        }

        private static bool Usable(CoefficientDto k) =>
            k != null && k.varied && k.direction == "positive" && k.weight_raw > 0 && !k.interval_includes_zero;

        // ---- History ----

        private void RenderHistory()
        {
            _history.Clear();
            ModelHistoryDto h = LastHistory;
            if (h == null || h.count == 0)
            {
                _historyNote.text = "No models trained yet.";
                Hide(_history);
                return;
            }
            _historyNote.text = $"{h.count} model(s), newest first. Only the active model is used for predictions; older ones are kept for reproducibility.";
            Row(_history, true, "Version", "Status", "Comparisons", "Scenarios", "Trained (UTC) / diagnostic accuracy");
            foreach (ModelHistoryItemDto item in h.models)
                Row(_history, false, item.model_version, item.status, item.unique_comparisons.ToString(Inv), item.scenario_count.ToString(Inv),
                    item.trained_utc + (item.diagnostic_available ? $" | LOSO accuracy {Pct(item.diagnostic_accuracy)} (n={item.diagnostic_n})" : " | no diagnostic"));
            Show(_history);
        }

        // ---- Suggestions ----

        public void Suggest()
        {
            if (!_suggest.enabledSelf || _ranking) return;
            PlanningSession s = _app.Session;
            CandidateSet set = _app.GenerateCandidates(s.Baseline.Seed);
            _suggestList.Clear();
            LastRank = null;
            _lastSet = set;
            string counts = $"Generated {set.Candidates.Count} feasible distinct candidate(s) from {set.Attempts} attempt(s) " +
                            $"({set.GeneratorVersion}, seed {set.Seed}); dropped {set.Infeasible} infeasible, {set.Duplicates} duplicate and " +
                            $"{set.NearDuplicates} near-duplicate design(s).";
            if (set.Candidates.Count < 2)
            {
                _suggestStatus.text = counts + " At least two are needed to rank, so nothing was sent.";
                return;
            }
            _ranking = true;
            _suggestStatus.text = counts + " Waiting for this scenario to reach the backend...";
            UpdateButtons();
            string scenarioId = s.Baseline.ScenarioId;
            _app.Learning.WhenReady(() => _app.IsDelivered(OutboxKinds.Scenario, scenarioId), SyncWaitSeconds, ready =>
            {
                if (!ready)
                {
                    _ranking = false;
                    _suggestStatus.text = counts + " The scenario has not reached the backend yet, so nothing was ranked. Try again shortly.";
                    UpdateButtons();
                    return;
                }
                _suggestStatus.text = counts + " Ranking with your model...";
                _app.Learning.RankCandidates(RankCandidatesRequestDto.From(set, scenarioId, SuggestionCount), r =>
                {
                    _ranking = false;
                    if (r.Ok)
                    {
                        LastRank = r.Body;
                        RenderSuggestions(counts);
                    }
                    else
                    {
                        LastError = $"{r.Code}: {r.Message}";
                        _suggestStatus.text = counts + $" Ranking refused ({r.Code}): {r.Message}";
                    }
                    UpdateButtons();
                });
            });
        }

        private void RenderSuggestions(string counts)
        {
            RankResponseDto r = LastRank;
            _suggestList.Clear();
            _suggestBanner.text = r.banner + (r.scenario_in_training_set
                ? " This scenario contributed comparisons to the model's training data."
                : " This scenario was not part of the model's training data.");
            _suggestStatus.text = counts + $" The model ranked {r.ranked}, skipped {r.skipped_near_duplicates} near-duplicate(s) and shows " +
                                  $"{r.returned} (model {r.model_version}). {r.caveat}";
            foreach (SuggestionDto sug in r.suggestions)
            {
                var card = new VisualElement();
                card.AddToClassList("suggest-card");
                card.Add(UiFormat.Text($"Suggestion {sug.rank}: {sug.description}", "suggest-title"));
                card.Add(UiFormat.Text(
                    $"Park access {(sug.access_defined ? Pct(sug.access_pct / 100.0) : "N/A")} | housing {sug.housing_units} units | " +
                    $"park share {Pct(sug.park_share_pct / 100.0)} | cost {sug.spent_credits} credits | " +
                    $"original housing removed {sug.lost_original_housing_units} | changed parcels {sug.changed_cell_ids.Count}", "body-text"));
                card.Add(UiFormat.Text(Contributions(sug), "hint"));
                if (sug.has_next)
                    card.Add(UiFormat.Text($"Model probability you would prefer this over suggestion {sug.rank + 1}: {Pct(sug.p_over_next)}.", "hint"));
                var row = new VisualElement();
                row.AddToClassList("row");
                string id = sug.candidate_id, hash = sug.state_hash;
                bool isCurrent = _app.Session != null && _app.Session.Current.ContentHash() == hash;
                var use = new Button(() => Apply(id, hash)) { text = isCurrent ? "Already your current design" : "Use as my design (undoable)" };
                use.AddToClassList("small-button");
                use.SetEnabled(!isCurrent);
                row.Add(use);
                card.Add(row);
                _suggestList.Add(card);
            }
        }

        private static string Contributions(SuggestionDto sug)
        {
            var parts = new List<string>();
            foreach (ContributionDto c in sug.contributions)
                if (Math.Abs(c.contribution) > 1e-9)
                    parts.Add($"{c.label} {c.contribution.ToString("+0.000;-0.000", Inv)}");
            return $"Model score {sug.utility.ToString("0.000", Inv)} relative to the baseline" +
                   (parts.Count > 0 ? ": " + string.Join(", ", parts) : string.Empty) + ".";
        }

        /// <summary>Loads a ranked candidate after checking it is exactly the design the backend ranked.</summary>
        public bool Apply(string candidateId, string stateHash)
        {
            CandidateDesign chosen = null;
            if (_lastSet != null)
                foreach (CandidateDesign c in _lastSet.Candidates)
                    if (c.CandidateId == candidateId) chosen = c;
            if (chosen == null || chosen.StateHash != stateHash || LastRank == null)
            {
                _ui.ShowMessage("That suggestion is no longer available; generate suggestions again.", true);
                return false;
            }
            CommandOutcome outcome = _app.ApplySuggestion(chosen, LastRank.model_version);
            if (outcome.Accepted) _ui.CloseOverlay(_screen);
            return outcome.Accepted;
        }

        public bool ApplyRank(int rank)
        {
            if (LastRank == null) return false;
            foreach (SuggestionDto s in LastRank.suggestions)
                if (s.rank == rank) return Apply(s.candidate_id, s.state_hash);
            return false;
        }

        // ---- Buttons ----

        public void UpdateButtons()
        {
            string reason = TrainBlockReason();
            _train.SetEnabled(reason == null);
            _train.tooltip = reason ?? "Fits a new model on every eligible comparison stored by the local backend.";
            if (reason != null && !_training && (_trainStatus.text.Length == 0 || _trainStatus.text.StartsWith("Train button", StringComparison.Ordinal)))
                _trainStatus.text = "Train button unavailable: " + reason;
            else if (reason == null && _trainStatus.text.StartsWith("Train button", StringComparison.Ordinal))
                _trainStatus.text = string.Empty;

            _evalNote.text = _app.Health != null && _app.Health.EvaluationOpen
                ? "A blinded test is running. Training is paused until you finish it."
                : EvaluationNote;

            string suggestReason = SuggestBlockReason();
            _suggest.SetEnabled(suggestReason == null);
            _suggest.tooltip = suggestReason ?? "Generates seeded feasible candidates for this scenario and ranks them with your model.";
            if (suggestReason != null && !_ranking && LastRank == null) _suggestStatus.text = suggestReason;
        }

        private string TrainBlockReason()
        {
            if (!_app.Learning.Available) return _app.Learning.UnavailableReason;
            if (_training) return "training is in progress.";
            if ((_app.Health != null && _app.Health.EvaluationOpen) || (LastReadiness != null && LastReadiness.evaluation_open))
                return "a blinded test is running. Finish it first, so the model being tested does not change.";
            if (_app.Outbox.PendingCount > 0)
                return $"{_app.Outbox.PendingCount} local record(s) are still syncing; training waits until the backend has all your decisions.";
            if (LastReadiness == null) return "checking whether there is enough data...";
            if (!LastReadiness.can_train)
                return LastReadiness.reasons.Count > 0 ? LastReadiness.reasons[0].message : "not enough varied comparisons yet.";
            return null;
        }

        private string SuggestBlockReason()
        {
            if (_app.Session == null) return "Start a challenge to get suggestions for it.";
            if (!_app.Learning.Available) return _app.Learning.UnavailableReason;
            if (_ranking) return "Ranking in progress...";
            if (LastCurrent == null || !LastCurrent.has_model) return "Suggestions need a trained model; none exists, so none are shown.";
            return null;
        }

        // ---- Helpers ----

        private static string Pct(double fraction) => (fraction * 100).ToString("0.0", Inv) + "%";

        private static void Show(VisualElement e) => e.RemoveFromClassList("hidden");
        private static void Hide(VisualElement e) => e.AddToClassList("hidden");

        private static void Row(VisualElement table, bool header, string name, string a, string b, string c, string text)
        {
            var row = new VisualElement();
            row.AddToClassList("ctable-row");
            if (header) row.AddToClassList("ctable-header");
            row.Add(UiFormat.Text(name, "ltable-name"));
            row.Add(UiFormat.Text(a, "ltable-num"));
            row.Add(UiFormat.Text(b, "ltable-num"));
            row.Add(UiFormat.Text(c, "ltable-num"));
            row.Add(UiFormat.Text(text, "ltable-text"));
            table.Add(row);
        }
    }
